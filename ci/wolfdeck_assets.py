"""Build flash-resident artwork: indexed RGB565 + compressed browser JPEG.

No image decoding, filesystem mount or full-screen framebuffer at runtime.
Run with Pillow 12.3.0 to regenerate the checked-in assets.
"""
from pathlib import Path
from PIL import Image,ImageOps
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/wolfdeck'

def array(name,ctype,values,columns=24):
    lines=[f'static const {ctype} {name}[] PROGMEM={{']
    width=4 if ctype=='uint16_t' else 2
    for p in range(0,len(values),columns):
        lines.append(' '+','.join(f'0x{v:0{width}x}' for v in values[p:p+columns])+',')
    return '\n'.join(lines+['};'])

def fitted_screen():
    # The supplied 320x240 crops have already lost the wolf's lower face.
    # Recover the complete composition from the larger source, with no zoom.
    with Image.open(ASSETS/'source/wolfdeck_web_background.jpg') as source:
        fitted=ImageOps.contain(source.convert('RGB'),(320,240),Image.Resampling.LANCZOS)
    canvas=Image.new('RGB',(320,240),(0,0,8))
    x=(320-fitted.width)//2;y=(240-fitted.height)//2
    canvas.paste(fitted,(x,y))
    return canvas,[x,y,fitted.width,fitted.height]

def generate():
    parts=['// Generated by ci/wolfdeck_assets.py. Source artwork is in assets/wolfdeck/source.',
           '#pragma once','#include <Arduino.h>','namespace WolfDeckAssets {']
    report={}
    for role in ['display','boot']:
        path=ASSETS/'source'/f'wolfdeck_{role}_320x240.jpg'
        img,rect=fitted_screen();assert img.size==(320,240)
        indexed=img.quantize(colors=256,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
        palette=indexed.getpalette();rgb565=[]
        for r,g,b in zip(palette[0::3],palette[1::3],palette[2::3]):
            rgb565.append(((r>>3)<<11)|((g>>2)<<5)|(b>>3))
        indices=indexed.tobytes()
        parts += [array(role+'Palette','uint16_t',rgb565),array(role+'Pixels','uint8_t',indices),
                  f'static_assert(sizeof({role}Pixels)==320*240,"Wrong {role} dimensions");']
        report[role]={'width':320,'height':240,'flash_bytes':len(indices)+len(rgb565)*2,
                      'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                      'render_source':'wolfdeck_web_background.jpg','fit':'contain','image_rect':rect}
    web=Image.open(ASSETS/'source/wolfdeck_web_background.jpg').convert('RGB')
    web.thumbnail((1280,800),Image.Resampling.LANCZOS)
    target=ASSETS/'web/wolfdeck_web_background.jpg'
    web.save(target,quality=78,optimize=True,progressive=True,subsampling=2)
    data=target.read_bytes()
    parts += [array('webJpg','uint8_t',data),'}','']
    report['web']={'width':web.width,'height':web.height,'flash_bytes':len(data),
                   'sha256':hashlib.sha256(data).hexdigest(),
                   'source_sha256':hashlib.sha256((ASSETS/'source/wolfdeck_web_background.jpg').read_bytes()).hexdigest()}
    report['runtime_row_buffer_bytes']=320*2
    (ROOT/'src/v62_wolfdeck_assets.h').write_text('\n'.join(parts))
    (ASSETS/'manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
if __name__=='__main__':generate()
