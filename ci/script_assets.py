"""Embed curated scripts + their instructions; offline and independent of LittleFS."""
from pathlib import Path
import json,hashlib,sys
r=Path(__file__).resolve().parents[1];root=r/'scripts';items=json.loads((root/'manifest.json').read_text())
s='// Generated by ci/script_assets.py.\n#pragma once\n#include <Arduino.h>\nnamespace V62ScriptAssets {\nstruct File {const char *folder,*name,*runtime,*source,*license,*content,*guide;};\n'
for n,item in enumerate(items):
 data=(root/item['folder']/item['name']).read_bytes();assert hashlib.sha256(data).hexdigest()==item['sha256']
 for key,value in [('content',data.decode()),('guide',(root/item['guide_file']).read_text())]:s+=f'static const char {key}_{n}[] PROGMEM='+json.dumps(value)+';\n'
s+='static const File files[]={\n'
for n,i in enumerate(items):s+=' {'+','.join(json.dumps(i[k]) for k in ['folder','name','runtime','source','license'])+f',content_{n},guide_{n}'+'},\n'
s+='};\nstatic constexpr size_t Count=sizeof(files)/sizeof(files[0]);\n}\n'
p=r/'src/v62_script_assets.h'
if '--check' in sys.argv:assert p.read_text()==s,'Run python ci/script_assets.py'
else:p.write_text(s)
print('Embedded',len(items),'scripts and their guides')
