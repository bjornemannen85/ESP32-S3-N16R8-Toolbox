#!/usr/bin/env python3
"""Embed the checked-in icon pack for TFT + web; no raster dependencies."""
from pathlib import Path
import json,re,argparse
ROOT=Path(__file__).resolve().parents[1]
def generate():
 d=ROOT/'assets/wolfdeck/icons';m=json.loads((d/'manifest.json').read_text());ids=[i['id'] for i in m['icons']]
 text='// Generated by ci/wolfdeck_icon_firmware.py. Do not edit.\n#pragma once\n#include <cstring>\n#include "../assets/wolfdeck/icons/wolfdeck_icons_24.h"\nnamespace V62Icons {\nstruct Icon {const char *id;const uint8_t *bits;const char *svg;size_t length;uint16_t color;};\n'
 for i in m['icons']:
  name=i['id'].replace('-','_');svg=(d/i['svg']).read_text();text+=f'static const char svg_{name}[] PROGMEM='+json.dumps(svg)+';\n'
 text+='static const Icon icons[]={\n'
 for i in m['icons']:
  name=i['id'].replace('-','_');c=int(i['color'][1:],16);color=((c>>19)<<11)|(((c>>10)&63)<<5)|((c>>3)&31)
  text+=f' {{"{i["id"]}",WolfDeckIcons24::{name},svg_{name},sizeof(svg_{name})-1,0x{color:04x}}},\n'
 text+='};\nstatic constexpr size_t Count=sizeof(icons)/sizeof(icons[0]);\n'
 text+='inline const Icon &get(const char *id){for(const auto &i:icons)if(id&&std::strcmp(id,i.id)==0)return i;return icons['+str(ids.index('system'))+'];}\n'
 text+='struct Route {const char *path;uint8_t icon;};\nstatic const Route routes[]={\n'
 for path,key in sorted(m['routes'].items()):text+=f' {{"{path}",{ids.index(key)}}},\n'
 text+='};\ninline const Icon &route(const char *path){for(const auto &r:routes)if(path&&std::strcmp(path,r.path)==0)return icons[r.icon];return get("system");}\n'
 pages=[p.strip() for p in re.search(r'enum Page \{([^}]+)',(ROOT/'src/main.cpp').read_text())[1].split(',') if p.strip()!='PAGE_COUNT']
 for name,values in [('pages',[m['native_pages'][p] for p in pages]),('categories',m['category_icons']),('home',m['home_icons'])]:
  text+='static const uint8_t '+name+'[]={'+','.join(str(ids.index(k)) for k in values)+'};\n'
  fallback='get("all-tools")' if name=='categories' else 'get("system")'
  text+=f'inline const Icon &{name}Icon(int index){{return index>=0&&size_t(index)<sizeof({name})?icons[{name}[index]]:{fallback};}}\n'
 text+='template<class LCD> inline void draw(LCD &lcd,const Icon &icon,int x,int y){lcd.drawBitmap(x,y,icon.bits,24,24,icon.color);}\n}\n'
 return text
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();target=ROOT/'src/v62_icons.h';value=generate()
 if a.check:assert target.read_text()==value,'Regenerate src/v62_icons.h'
 else:target.write_text(value)
 print('Icon firmware table checked: TFT 24px and SVG flash data')
