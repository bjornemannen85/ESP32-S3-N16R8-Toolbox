"""Extract API fields from the actual handlers; CI rejects a stale catalog."""
from pathlib import Path
import re, sys
root=Path(__file__).resolve().parents[1]
entries={}
sources=list((root/'src').glob('v61*.h'))+[root/'src'/n for n in ['v62_modules.h','v62_script_apps.h','v62_app_content.h']]
for p in sorted(sources):
    text=p.read_text()
    routes=list(re.finditer(r's.on\("([^"]+)",\s*(HTTP_GET|HTTP_POST)',text))
    for i,m in enumerate(routes):
        body=text[m.end():routes[i+1].start() if i+1<len(routes) else len(text)]
        params=list(dict.fromkeys(re.findall(r's.arg\("([^"]+)"\)',body)))
        entries.setdefault((m[1],m[2]),params)
lines=['// Generated by ci/catalog.py. Do not edit.', '#pragma once',
       'struct V62Parameters { const char *path; HTTPMethod method; const char *fields; };',
       'static const V62Parameters v62Parameters[]={']
for (path,method),params in sorted(entries.items()):
    lines.append(' {"%s",%s,"%s"},'%(path,method,','.join(params)))
lines+=['};','']
out='\n'.join(lines); dest=root/'src/v62_parameters.h'
if '--check' in sys.argv:
    assert dest.read_text()==out, 'Run python ci/catalog.py'
else: dest.write_text(out)
print(f'Catalog: {len(entries)} existing routes')
